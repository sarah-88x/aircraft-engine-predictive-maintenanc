from __future__ import annotations

import json
from datetime import datetime, timezone

from pyspark.sql import SparkSession
from pyspark.sql import functions as F
from pyspark.sql.types import (
    DoubleType,
    StringType,
    StructField,
    StructType,
    TimestampType,
)


def build_telemetry_schema() -> StructType:
    """Define the structured schema for incoming aircraft engine telemetry messages."""
    return StructType([
        StructField("timestamp", TimestampType(), True),
        StructField("unit", DoubleType(), True),
        StructField("cycle", DoubleType(), True),
        StructField("rul", DoubleType(), True),
        StructField("dataset", StringType(), True),
        StructField("sensor_T24", DoubleType(), True),
        StructField("sensor_T30", DoubleType(), True),
        StructField("sensor_T48", DoubleType(), True),
        StructField("sensor_T50", DoubleType(), True),
        StructField("sensor_P15", DoubleType(), True),
        StructField("sensor_P2", DoubleType(), True),
        StructField("sensor_P21", DoubleType(), True),
        StructField("sensor_P24", DoubleType(), True),
        StructField("sensor_Ps30", DoubleType(), True),
        StructField("sensor_Nf", DoubleType(), True),
        StructField("sensor_Nc", DoubleType(), True),
        StructField("sensor_Wf", DoubleType(), True),
        StructField("W_alt", DoubleType(), True),
        StructField("W_Mach", DoubleType(), True),
        StructField("W_TRA", DoubleType(), True),
        StructField("W_T2", DoubleType(), True),
        StructField("Fc", DoubleType(), True),
    ])


def test_schema_compatibility() -> bool:
    """Validate telemetry schema parsing and Dead-Letter Queue (DLQ) quarantine routing."""
    print("=" * 70)
    print("     VERIFYING STREAMING COMPATIBILITY: PRODUCER <-> SPARK STREAMING     ")
    print("=" * 70)

    # Initialize a local Spark session for validation testing
    spark = (
        SparkSession.builder
        .appName("StreamingCompatibilityCheck")
        .master("local[1]")
        .getOrCreate()
    )
    spark.sparkContext.setLogLevel("ERROR")

    try:
        # 1. Sample compliant telemetry payload generated by producer.py
        valid_telemetry = {
            "timestamp": datetime.now(timezone.utc).isoformat(),
            "unit": 1.0,
            "cycle": 15.0,
            "rul": 84.0,
            "dataset": "N-CMAPSS_DS01-005",
            "sensor_T24": 642.55,
            "sensor_T30": 1585.20,
            "sensor_T48": 1400.10,
            "sensor_T50": 553.80,
            "sensor_P15": 14.62,
            "sensor_P2": 14.0,
            "sensor_P21": 14.62,
            "sensor_P24": 21.61,
            "sensor_Ps30": 554.36,
            "sensor_Nf": 2388.06,
            "sensor_Nc": 9046.19,
            "sensor_Wf": 1.30,
            "W_alt": 10000.0,
            "W_Mach": 0.6,
            "W_TRA": 70.0,
            "W_T2": 518.67,
            "Fc": 1.0,
        }

        # 2. Sample corrupted payload missing mandatory schema fields to verify DLQ routing
        corrupted_telemetry = {
            "timestamp": datetime.now(timezone.utc).isoformat(),
            "corrupted_payload": "INVALID_DATA_FORMAT_NO_UNIT",
            "anomaly_flag": True,
        }

        # Construct test dataset containing valid, corrupted, and non-JSON string entries
        test_records = [
            ("valid-key-1", json.dumps(valid_telemetry)),
            ("corrupted-key-2", json.dumps(corrupted_telemetry)),
            ("malformed-key-3", "THIS IS NOT VALID JSON AT ALL"),
        ]

        df = spark.createDataFrame(test_records, ["key", "value"])
        schema = build_telemetry_schema()

        # Parse JSON payloads into defined schema structure
        parsed_df = df.select(
            F.col("key"),
            F.col("value").alias("raw_json"),
            F.from_json(F.col("value"), schema).alias("data"),
        )

        # Segregate compliant messages from malformed entries requiring dead-letter queue routing
        valid_df = parsed_df.filter(
            F.col("data.unit").isNotNull() & F.col("data.cycle").isNotNull()
        )
        dlq_df = parsed_df.filter(
            F.col("data").isNull()
            | F.col("data.unit").isNull()
            | F.col("data.cycle").isNull()
        )

        valid_count = valid_df.count()
        dlq_count = dlq_df.count()

        print(f"[*] Valid Messages Parsed   : {valid_count} (Expected: 1)")
        print(f"[*] Quarantine (DLQ) Routed : {dlq_count} (Expected: 2)")

        # Verify parsed field values and data types of the compliant message
        row = valid_df.select("data.*").collect()[0]
        assert row.unit == 1.0, "Unit mismatch"
        assert row.cycle == 15.0, "Cycle mismatch"
        assert row.sensor_T30 == 1585.20, "Sensor T30 mismatch"

        if valid_count == 1 and dlq_count == 2:
            print("[✔ PASS] Schema parsing & DLQ separation verified 100% successfully!")
            print("[✔ PASS] All fields are correctly typed (Double, Timestamp, String).")
            print("=" * 70)
            return True
        else:
            print("[✖ FAIL] Mismatch in message categorization.")
            print("=" * 70)
            return False

    finally:
        # Tear down the Spark context and release compute resources
        spark.stop()


if __name__ == "__main__":
    success = test_schema_compatibility()
    if not success:
        exit(1)